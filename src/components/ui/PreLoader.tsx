"use client";
import { useAnimationsStore } from "@/store/animations-store";
import { useGSAP } from "@gsap/react";
import gsap from "gsap";
import { CustomEase } from "gsap/CustomEase";
import { usePathname } from "next/navigation";
import { useEffect, useRef } from "react";

export const Preloader = () => {
  const container = useRef<HTMLDivElement>(null);
    

  const path = usePathname();
  const setStartNavAnimation = useAnimationsStore(
    (state) => state.setStartAnimation
  );

  useEffect(() => {
    if (path !== "/") {
      gsap.set(container.current, { display: "none" });
      setStartNavAnimation(true);
    }
  }, [path, setStartNavAnimation]);

  useGSAP(
    () => {
      gsap.registerPlugin(CustomEase);

      if (sessionStorage.getItem("preloaded")) {
        setStartNavAnimation(true);
        gsap.set(container.current, { display: "none" });
        return;
      }

      if (!container.current) return;

      const tl = gsap.timeline({
        onUpdate: function () {
          //  setLoadStatus(Math.round(this.progress() * 100));
        },
        onComplete: () => {
       sessionStorage.setItem("preloaded", "true");

          if (container.current) container.current.style.display = "none";
          setStartNavAnimation(true);
        },
      });

      const paths = Array.from(
        container.current.querySelectorAll("path")
      ) as SVGPathElement[];

      paths.forEach((path) => {
        const totalLength = path.getTotalLength().toString();
        path.style.strokeDasharray = totalLength;
        path.style.strokeDashoffset = totalLength;
      });

      gsap.set(container.current, { opacity: 1 });

      tl.to(
        "#brand",
        {
          opacity: 1,
        },
        0
      )
        .to(
          [container.current],
          {
            backgroundColor: "#F2EEDF",
            ease: "power4.in",
            duration: 1,
          },
          0
        )
        /*  .from(
          loader.current,
          {
            textContent: 0,
            duration: 1.5,
            ease: "power4.out",
            snap: { textContent: 1 },

            onUpdate: function () {
              if (this.progress) {
                const progress = Math.round(this.progress() * 100);

                if (loader.current)
                  loader.current.textContent = progress.toString();
              }
            },
          },
          1
        ) */

        .to(
          paths,
          {
            strokeDashoffset: "0",
            duration: 1.5,
            stagger: 0.1,
            ease: "back.out",
          },
          1
        )

        .to(
          paths,
          {
            fill: "#A39383",
            stroke: "transparent",
            delay: 0.1,
            stagger: 0.1,
          },
          1
        )
        .to(
          ".line",
          {
            scaleX: 1,
            transformOrigin: "center",
            duration: 2,
            ease: "power4.in",
          
          },
          2
        )

        .to(
          ".line",
          {
            height: "100vh",
            backgroundColor: "#F9FBF8",
            transformOrigin: "center",
            duration: 1.5,
            delay:1,
            ease: "power4.in",
          },
          3
        )
        .to(
          ".text",
          {
            y: 0,
            duration: 1,
            delay: -0.2,
            ease: "power4.inOut",
          },
          2
        )

        .to(
          [".text", "#brand"],
          {
            scale: 0,
            duration: 1,
            delay: 0.5,
            ease: "power4.inOut",
          },
          3
        );
    },
    {
      scope: container,
    }
  );

  return (
    <div
      style={{ clipPath: "polygon(0 0, 100% 0, 100% 100%, 0% 100%)" }}
      ref={container}
      className="fixed top-0 left-0 bg-color1   z-[150] w-screen h-[100dvh] lg:h-screen px-4 md:px-10 xl:px-32 opacity-0 flex items-center justify-center"
    >
      <div className=" relative w-full text-center self-center overflow-hidden   flex flex-col gap-5 md:-translate-y-5  justify-center items-center brand-container z-50  ">
        <SvgBrand
          className=" opacity-0 z-20 w-[90%]  md:w-[28rem]"
          id="brand"
        />

        <span className="block translate-y-full text-color2 text text-2xl ">
          Empodera tu belleza, yo te acompaño en el proceso
        </span>
      </div>

      <div className=" absolute  w-full bg-color2 h-0.5 scale-x-0 line left-1/2 top-1/2 -translate-y-1/2 -translate-x-1/2"></div>

      {/* <div className="w-full  h-1/2 flex flex-col justify-end pb-10 items-end brand-container absolute right-10 top-10 ">
        <div className="relative">
          <span ref={loader} className="text-4xl  text-black ">
            0
          </span>

          <span className="ml-1">%</span>
        </div>
      </div> */}
    </div>
  );
};

